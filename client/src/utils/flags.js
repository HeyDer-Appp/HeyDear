const ALL_COUNTRIES = [...PRIORITY, ...REST_ALPHABETICAL];

// Names in display order — Quiz.jsx appends its own trailing 'Other' option.
export const COUNTRY_LIST = ALL_COUNTRIES.map(([name]) => name);

// [name, dialCode] pairs, same order as COUNTRY_LIST — several countries
// legitimately share a dial code (US/Canada both '+1' etc.), which just
// means the phone country-code picker shows that code more than once.
export const DIAL_CODES = ALL_COUNTRIES.map(([name, , dial]) => [name, dial]);

const COUNTRY_CODES = Object.fromEntries(ALL_COUNTRIES.map(([name, iso]) => [name, iso]));

// Windows doesn't ship flag glyphs in its emoji font, so a Unicode
// regional-indicator flag emoji just renders as plain "NZ"/"IN" letters in
// a box there instead of an actual flag — an <img> pointing at a real flag
// image renders identically on every OS instead.
export function flagUrl(countryName) {
  const code = COUNTRY_CODES[countryName];
  return code ? `https://flagcdn.com/24x18/${code}.png` : null;
}
